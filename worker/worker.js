export default {
  async fetch(request, env, ctx) {
    // Handle CORS preflight
    if (request.method === 'OPTIONS') {
      return new Response(null, {
        headers: {
          'Access-Control-Allow-Origin': '*',
          'Access-Control-Allow-Methods': 'GET, OPTIONS',
          'Access-Control-Allow-Headers': '*',
          'Access-Control-Max-Age': '86400',
        }
      });
    }

    try {
      const userAgent = request.headers.get('user-agent')?.toLowerCase() || '';
      const url = new URL(request.url);
      const referrer = request.headers.get('referer') || '';
      const acceptHeader = request.headers.get('accept') || '';
      const isJina = referrer.includes('jina.ai');

      // Check if client explicitly requests plain text
      const wantsPlainText = acceptHeader.includes('text/plain');

      // Bot detection
      const isBot = 
        userAgent.includes('bot') || 
        userAgent.includes('crawler') || 
        userAgent.includes('spider') ||
        userAgent.includes('googlebot') ||
        userAgent.includes('bingbot') ||
        userAgent.includes('baidu') ||
        userAgent.includes('twitterbot') ||
        userAgent.includes('linkedinbot') ||
        userAgent.includes('slackbot') ||
        userAgent.includes('facebookexternalhit') ||
        userAgent.includes('facebot') ||
        request.headers.get('x-purpose')?.includes('preview') ||
        request.headers.has('x-fb-curl-type') ||
        /((facebook|twitter|linkedin|slack|discord|telegram)bot|social)/i.test(userAgent);

      // Browser detection  
      const isBrowser = 
        userAgent.includes('mozilla') ||
        userAgent.includes('chrome') ||
        userAgent.includes('safari') ||
        userAgent.includes('opera') ||
        userAgent.includes('edge') ||
        userAgent.includes('firefox');

      // API reference generated by api-docs/build.mjs (api.jina.ai + r.jina.ai + s.jina.ai merged).
      // /                    browsers and bots get the Scalar page (below); curl & co. still get the meta-prompt
      // /api.md              the reference as Markdown
      // /openapi.json        merged OpenAPI spec
      // /api, /api/openapi.json  old addresses, redirected
      // Every other path falls through to the meta-prompt logic below, unchanged.
      const apiDocsBase = (env && env.API_DOCS_BASE) || 'https://raw.githubusercontent.com/jina-ai/meta-prompt/refs/heads/main/api-docs';
      const moved = { '/api': '/', '/api/': '/', '/api/openapi.json': '/openapi.json' };
      if (moved[url.pathname]) {
        return Response.redirect(new URL(moved[url.pathname], url).toString(), 301);
      }
      let apiDoc = null;
      if (url.pathname === '/api.md') {
        apiDoc = ['api.md', 'text/markdown; charset=utf-8'];
      } else if (url.pathname === '/openapi.json') {
        apiDoc = ['openapi.json', 'application/json; charset=utf-8'];
      }
      if (apiDoc) {
        const docResponse = await fetch(`${apiDocsBase}/${apiDoc[0]}`, { cf: { cacheTtl: 300, cacheEverything: true } });
        if (!docResponse.ok) {
          throw new Error(`Failed to fetch api-docs/${apiDoc[0]}`);
        }
        return new Response(docResponse.body, {
          headers: {
            'content-type': apiDoc[1],
            'cache-control': 'public, max-age=300',
            'vary': 'User-Agent, Accept',
            'Access-Control-Allow-Origin': '*',
            'Access-Control-Allow-Methods': 'GET, OPTIONS',
            'Access-Control-Allow-Headers': '*',
          }
        });
      }

      // Determine version from path or get default
      let version;
      const match = url.pathname.match(/^\/v(\d+)$/);
      if (match) {
        version = `v${match[1]}`;
      } else {
        // Fetch default version from GitHub
        const defaultVersionResponse = await fetch('https://raw.githubusercontent.com/jina-ai/meta-prompt/refs/heads/main/default');
        if (!defaultVersionResponse.ok) {
          throw new Error('Failed to fetch default version');
        }
        version = (await defaultVersionResponse.text()).trim();
      }

      // Fetch headers configuration
      const headersResponse = await fetch('https://raw.githubusercontent.com/jina-ai/meta-prompt/refs/heads/main/headers.json');
      if (!headersResponse.ok) {
        throw new Error('Failed to fetch headers configuration');
      }
      const headersText = await headersResponse.text();
      const staticHeaders = JSON.parse(headersText);

      // Fetch the meta prompt content
      const metaPromptResponse = await fetch(`https://raw.githubusercontent.com/jina-ai/meta-prompt/refs/heads/main/${version}.txt`);
      if (!metaPromptResponse.ok) {
        throw new Error(`Failed to fetch meta prompt for version ${version}`);
      }
      const metaPromptText = await metaPromptResponse.text();

      // Combine and deduplicate headers
      const commonHeaders = {
        ...staticHeaders,
        'Access-Control-Allow-Origin': '*',
        'Access-Control-Allow-Methods': 'GET, OPTIONS',
        'Access-Control-Allow-Headers': '*',
        'x-meta-prompt-version': version,
        'x-debug-accept': acceptHeader,
        'x-debug-user-agent': userAgent,
        'x-debug-is-browser': String(isBrowser),
        'x-debug-is-bot': String(isBot),
        'x-debug-referrer': referrer,
        'x-generated-at': new Date().toISOString()
      };

      // If client explicitly requests plain text, serve it regardless of user agent
      if (wantsPlainText) {
        return new Response(metaPromptText, {
          headers: {
            'content-type': 'text/plain; charset=utf-8',
            ...commonHeaders,
          }
        });
      }

      // Show HTML for both browsers and bots
      if (isBot || isBrowser) {
        // The root page in a browser is the API reference; /v{n} keeps the meta-prompt HTML view.
        if (url.pathname === '/') {
          const pageResponse = await fetch(`${apiDocsBase}/index.html`, { cf: { cacheTtl: 300, cacheEverything: true } });
          if (!pageResponse.ok) {
            throw new Error('Failed to fetch api-docs/index.html');
          }
          return new Response(pageResponse.body, {
            headers: {
              'content-type': 'text/html; charset=utf-8',
              ...commonHeaders,
            }
          });
        }

        // Fetch HTML template
        const templateResponse = await fetch('https://raw.githubusercontent.com/jina-ai/meta-prompt/refs/heads/main/index.html');
        if (!templateResponse.ok) {
          throw new Error('Failed to fetch HTML template');
        }
        let htmlTemplate = await templateResponse.text();

        // Replace placeholders in the template
        htmlTemplate = htmlTemplate
          .replace('{{VERSION}}', version !== 'index' ? ` (${version})` : '')
          .replace(/\{\{CURL_COMMAND\}\}/g, `curl docs.jina.ai${version === 'v1' ? '' : `/${version}`}`)
          .replace('{{META_PROMPT}}', metaPromptText);

        return new Response(htmlTemplate, {
          headers: {
            'content-type': 'text/html; charset=utf-8',
            ...commonHeaders,
          }
        });
      }

      // Serve plain text for programmatic requests
      return new Response(metaPromptText, {
        headers: {
          'content-type': 'text/plain; charset=utf-8',
          ...commonHeaders,
        }
      });

    } catch (error) {
      console.error('Error:', error);
      return new Response(`Error fetching Jina AI meta-prompt: ${error.message}`, { 
        status: 500,
        headers: {
          'content-type': 'text/plain',
          'x-error-description': error.message,
          'x-content-audience': 'llm'
        }
      });
    }
  },
};
